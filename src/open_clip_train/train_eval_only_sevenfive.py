class WdsImageTextMapper:
    def __init__(
        self,
        transform,
        tokenizer,
        caption_key,
        long_caption_key=None,
        long_caption_mode="none",
        long_caption_chunk_tokens=75,
        long_caption_chunk_overlap=8,
        long_caption_prepend_title=False,
        long_caption_sample_prob=0.5,
        short_caption_sample_prob=0.5,
        rewrite_caption_sample_prob=0.25,
        semantic_lookup=None,
        semantic_replace_mode="both",
        semantic_replace_structure_prob=1.0,
        semantic_replace_cell_prob=1.0,
    ):
        self.transform = transform
        self.tokenizer = tokenizer
        self.caption_key = caption_key
        self.long_caption_key = long_caption_key
        self.long_caption_mode = long_caption_mode
        self.long_caption_chunk_tokens = long_caption_chunk_tokens
        self.long_caption_chunk_overlap = long_caption_chunk_overlap
        self.long_caption_prepend_title = long_caption_prepend_title
        self.long_caption_sample_prob = long_caption_sample_prob
        self.short_caption_sample_prob = short_caption_sample_prob
        self.rewrite_caption_sample_prob = rewrite_caption_sample_prob
        self.semantic_lookup = semantic_lookup
        self.semantic_replace_mode = semantic_replace_mode
        self.semantic_replace_structure_prob = semantic_replace_structure_prob
        self.semantic_replace_cell_prob = semantic_replace_cell_prob
        self._check_args()

    def _check_args(self):
        if self.long_caption_mode not in (
            "none",
            "random-chunk",
            "title-or-random-chunk",
            "title-or-full-long-caption",
            "three-way",
        ):
            raise ValueError(f"Unsupported long_caption_mode: {self.long_caption_mode}")
        if self.long_caption_mode != "none" and not self.long_caption_key:
            raise ValueError("train_long_caption_key is required when train_long_caption_mode is not 'none'.")
        if self.long_caption_mode != "none" and not hasattr(self.tokenizer, "encode"):
            raise TypeError("Long caption chunking requires a tokenizer with an encode() method.")
        if self.long_caption_chunk_tokens <= 0:
            raise ValueError("long_caption_chunk_tokens must be positive.")
        if self.long_caption_chunk_overlap < 0:
            raise ValueError("long_caption_chunk_overlap must be non-negative.")
        if not 0.0 <= self.long_caption_sample_prob <= 1.0:
            raise ValueError("long_caption_sample_prob must be between 0 and 1.")
        if self.long_caption_mode == "three-way":
            for prob_name, prob_value in (
                ("short_caption_sample_prob", self.short_caption_sample_prob),
                ("rewrite_caption_sample_prob", self.rewrite_caption_sample_prob),
            ):
                if not 0.0 <= prob_value <= 1.0:
                    raise ValueError(f"{prob_name} must be between 0 and 1.")
            if not math.isclose(
                self.long_caption_sample_prob
                + self.short_caption_sample_prob
                + self.rewrite_caption_sample_prob,
                1.0,
                abs_tol=1e-6,
            ):
                raise ValueError("In three-way mode, the three sample probabilities must sum to 1.")
        if self.semantic_replace_mode not in ("both", "structure-only", "cell-only", "none", "random"):
            raise ValueError(f"Unsupported semantic_replace_mode: {self.semantic_replace_mode}")
        if not 0.0 <= self.semantic_replace_structure_prob <= 1.0:
            raise ValueError("semantic_replace_structure_prob must be between 0 and 1.")
        if not 0.0 <= self.semantic_replace_cell_prob <= 1.0:
            raise ValueError("semantic_replace_cell_prob must be between 0 and 1.")

    @staticmethod
    def _string_value(value):
        if value is None:
            return ""
        if isinstance(value, bytes):
            return value.decode("utf-8", errors="replace").strip()
        return str(value).strip()

    @staticmethod
    def _json_value(value):
        if value is None:
            return {}
        if isinstance(value, bytes):
            value = value.decode("utf-8", errors="replace")
        if isinstance(value, str):
            return json.loads(value)
        return value if isinstance(value, dict) else {}

    def _decode_tokens(self, token_ids):
        if not token_ids:
            return ""
        if hasattr(self.tokenizer, "decode"):
            return self.tokenizer.decode(token_ids).strip()
        return ""

    def _random_token_chunk(self, text, token_budget):
        token_ids = self.tokenizer.encode(text)
        if len(token_ids) <= token_budget:
            return self._decode_tokens(token_ids)

        overlap = min(self.long_caption_chunk_overlap, max(token_budget - 1, 0))
        stride = max(1, token_budget - overlap)
        last_start = len(token_ids) - token_budget
        starts = list(range(0, last_start + 1, stride))
        if starts[-1] != last_start:
            starts.append(last_start)
        start = random.choice(starts)
        return self._decode_tokens(token_ids[start : start + token_budget])

    def _replacement_probs(self):
        """Per-sample structure/cell replacement probabilities for the current mode."""
        if self.semantic_replace_mode == "both":
            return 1.0, 1.0
        if self.semantic_replace_mode == "structure-only":
            return 1.0, 0.0
        if self.semantic_replace_mode == "cell-only":
            return 0.0, 1.0
        if self.semantic_replace_mode == "none":
            return 0.0, 0.0
        return self.semantic_replace_structure_prob, self.semantic_replace_cell_prob

    def _build_replaced_title(self, title, metadata):
        """Rewrite 'a microscopy photo of {structure}_of_{cell}' by substituting the
        structure and/or cell names with their semantic captions.

        Compound structures like ``Actin_filaments_and_Cytosol`` are decomposed on
        ``_and_`` by the lookup, and each component's caption is concatenated.
        The original title template (prefix, ``_of_`` separator, suffix) is preserved
        whenever the canonical names can be located inside the title; otherwise the
        canonical MicroPool811 template is used.
        """
        if self.semantic_lookup is None or not title:
            return title
        structure = self._string_value(metadata.get("canonical_organelle"))
        cell = self._string_value(metadata.get("canonical_cell"))
        if not structure or not cell:
            return title

        structure_caption = self.semantic_lookup.structure_caption(structure)
        cell_caption = self.semantic_lookup.cell_caption(cell)
        structure_prob, cell_prob = self._replacement_probs()
        replace_structure = bool(structure_caption) and random.random() < structure_prob
        replace_cell = bool(cell_caption) and random.random() < cell_prob
        if not replace_structure and not replace_cell:
            return title

        structure_part = structure_caption if replace_structure else structure
        cell_part = cell_caption if replace_cell else cell

        struct_start = title.find(structure)
        cell_start = title.find(cell, struct_start + len(structure)) if struct_start >= 0 else -1
        if struct_start < 0 or cell_start < 0:
            # Cannot locate the canonical names in the title; fall back to the standard template.
            return f"a microscopy photo of {structure_part}_of_{cell_part}"

        struct_end = struct_start + len(structure)
        cell_end = cell_start + len(cell)
        separator = title[struct_end:cell_start]  # "_of_"
        return f"{title[:struct_start]}{structure_part}{separator}{cell_part}{title[cell_end:]}"

    def _training_title(self, title, metadata):
        """Title-branch text: the original title with structure/cell semantic replacement."""
        if self.semantic_lookup is None:
            return title
        return self._build_replaced_title(title, metadata) or title

    def _supports_semantic_rewrite(self, metadata):
        """Whether the sample has a semantic rewrite caption available.

        MicroPool samples expose ``canonical_organelle``/``canonical_cell``, which is
        what the rewrite is built from. VLM samples carry neither, so no rewrite
        caption exists for them and their rewrite branch falls back to the full long
        caption (kept whole, never randomly chunked).
        """
        return bool(self._string_value(metadata.get("canonical_organelle"))) and bool(
            self._string_value(metadata.get("canonical_cell"))
        )

    def _build_three_way_text(self, title, metadata):
        """Three-way text mix: long caption / original short title / semantic-rewritten title.

        Branches are drawn with the three sample probabilities (validated to sum to 1):
        long_caption_sample_prob picks the full long caption, short_caption_sample_prob
        keeps the original title unchanged, and rewrite_caption_sample_prob applies the
        structure/cell semantic replacement. VLM samples have no rewrite caption, so
        their rewrite branch reuses the full long caption instead. When the long caption
        is missing the remaining branch weights are renormalised over short/rewrite.
        """
        long_caption = self._string_value(metadata.get(self.long_caption_key))
        if long_caption and random.random() < self.long_caption_sample_prob:
            return long_caption

        short_fraction = self.short_caption_sample_prob / (
            self.short_caption_sample_prob + self.rewrite_caption_sample_prob
        )
        if random.random() < short_fraction:
            return title
        if not self._supports_semantic_rewrite(metadata):
            # VLM samples carry no canonical structure/cell names, so there is no
            # rewrite caption; reuse the full long caption (no random chunking).
            return long_caption or title
        return self._training_title(title, metadata)

    def _build_training_text(self, title, metadata):
        if self.long_caption_mode == "none":
            return self._training_title(title, metadata)
        if self.long_caption_mode in ("title-or-random-chunk", "title-or-full-long-caption") and (
            random.random() >= self.long_caption_sample_prob
        ):
            return self._training_title(title, metadata)
        if self.long_caption_mode == "three-way":
            return self._build_three_way_text(title, metadata)

        long_caption = self._string_value(metadata.get(self.long_caption_key))
        if not long_caption:
            return self._training_title(title, metadata)

        if self.long_caption_mode == "title-or-full-long-caption":
            # Keep the full caption; the tokenizer truncates to the context length.
            return long_caption

        context_length = getattr(self.tokenizer, "context_length", None) or 77
        token_budget = min(self.long_caption_chunk_tokens, max(context_length - 2, 0))
        if token_budget <= 0:
            return self._training_title(title, metadata)

        chunk = self._random_token_chunk(long_caption, token_budget)
        if self.long_caption_prepend_title and title:
            return f"{self._training_title(title, metadata)}. {chunk}"
        return chunk or title

    def __call__(self, sample):
        title = self._string_value(sample.get(self.caption_key))
        metadata = self._json_value(sample.get("json"))
        text = self._build_training_text(title, metadata) or title or "missing caption"
        image = self.transform(sample["image"])
        text = self.tokenizer([text])[0]
        return {
            "image": image,
            "text": text,
        }


def filter_no_wds_caption_or_no_image(sample):
    has_image = any(key in sample for key in ("jpg", "jpeg", "png", "webp"))
    return has_image and "txt" in sample and "json" in sample


def filter_valid_mapped_sample(sample):
    return (
        isinstance(sample, dict)
        and isinstance(sample.get("image"), torch.Tensor)
        and isinstance(sample.get("text"), torch.Tensor)
    )


def collate_image_text_only(batch):
    batch = [sample for sample in batch if filter_valid_mapped_sample(sample)]
    if not batch:
        raise RuntimeError("All samples in a WebDataset batch were invalid after image/text mapping.")
    return default_collate(
        [
            {
                "image": sample["image"],
                "text": sample["text"],
            }
            for sample in batch
        ]
    )


def looks_like_wds(path):
    return any(part in path for part in (".tar", "{", "::"))


def build_wds_train_loader(args, preprocess_train, tokenizer, epoch=0, semantic_lookup=None):
    if args.train_num_samples is None:
        raise ValueError("--train-num-samples is required when --train-data points to WebDataset shards.")

    input_shards, _ = expand_urls(args.train_data)
    if not input_shards:
        raise ValueError(f"--train-data did not resolve to any WebDataset shards: {args.train_data}")
    if is_main_process(args):
        _LOGGER.info(
            "Resolved training shards | count=%d first=%s last=%s",
            len(input_shards),
            input_shards[0],
            input_shards[-1],
        )
    shared_epoch = SharedEpoch(epoch=epoch)
    balance_filter = None
    if args.metaclip_balance_counts:
        counts, counts_metadata = load_counts(
            args.metaclip_balance_counts,
            expected_source=args.metaclip_balance_source,
        )
        balance_filter = MetaClipBalanceFilter(
            counts,
            args.metaclip_balance_threshold,
            source=args.metaclip_balance_source,
            seed=args.seed + args.rank,
        )
        if is_main_process(args):
            _LOGGER.info(
                "MetaCLIP online balancing enabled | concepts=%d threshold=%d source=%s "
                "counted_samples=%s counts=%s",
                len(counts),
                args.metaclip_balance_threshold,
                args.metaclip_balance_source,
                counts_metadata.get("matched_samples"),
                args.metaclip_balance_counts,
            )

    if balance_filter is not None:
        shard_source = ResampledShards2(input_shards, deterministic=True, epoch=shared_epoch)
        shard_stages = [shard_source]
    else:
        shard_stages = [
            wds.SimpleShardList(input_shards),
            detshuffle2(seed=args.seed, epoch=shared_epoch),
            wds.split_by_node,
            wds.split_by_worker,
        ]

    pipeline = shard_stages + [
        tarfile_to_samples_nothrow,
        wds.shuffle(5000, initial=1000),
        wds.select(filter_no_wds_caption_or_no_image),
    ]
    if balance_filter is not None:
        pipeline.append(wds.select(balance_filter))
    pipeline += [
        wds.decode("pilrgb"),
        wds.rename(image="jpg;png;jpeg;webp", txt="txt", json="json", keep=False),
        wds.map(
            WdsImageTextMapper(
                preprocess_train,
                tokenizer,
                caption_key="txt",
                long_caption_key=args.train_long_caption_key,
                long_caption_mode=args.train_long_caption_mode,
                long_caption_chunk_tokens=args.long_caption_chunk_tokens,
                long_caption_chunk_overlap=args.long_caption_chunk_overlap,
                long_caption_prepend_title=args.long_caption_prepend_title,
                long_caption_sample_prob=args.long_caption_sample_prob,
                short_caption_sample_prob=args.short_caption_sample_prob,
                rewrite_caption_sample_prob=args.rewrite_caption_sample_prob,
                semantic_lookup=semantic_lookup,
                semantic_replace_mode=args.semantic_replace_mode,
                semantic_replace_structure_prob=args.semantic_replace_structure_prob,
                semantic_replace_cell_prob=args.semantic_replace_cell_prob,
            )
        ),
        wds.select(filter_valid_mapped_sample),
        wds.batched(args.batch_size, partial=False, collation_fn=collate_image_text_only),
    ]
    dataset = wds.DataPipeline(*pipeline)

    num_shards = len(input_shards)
    if num_shards < args.workers * args.world_size:
        raise RuntimeError(
            f"number of shards ({num_shards}) must be >= workers * world_size "
            f"({args.workers * args.world_size}); resolved from --train-data={args.train_data!r}"
        )
    global_batch_size = args.batch_size * args.world_size
    num_batches = args.train_num_samples // global_batch_size
    if num_batches <= 0:
        raise RuntimeError("Training dataloader has 0 batches. Reduce --batch-size or increase --train-num-samples.")
    num_workers = max(1, args.workers)
    num_worker_batches = math.ceil(num_batches / num_workers)
    num_batches = num_worker_batches * num_workers
    dataset = dataset.with_epoch(num_worker_batches)

    loader = wds.WebLoader(
        dataset,
        batch_size=None,
        shuffle=False,
        num_workers=args.workers,
        persistent_workers=args.persistent_workers and args.workers > 0,
        prefetch_factor=args.prefetch_factor if args.workers > 0 else None,
        timeout=args.dataloader_timeout if args.workers > 0 else 0,
    )
    return _LoaderWithLen(loader, num_batches), shared_epoch, args.train_num_samples


def setup_logging(log_dir, args):
    logger = logging.getLogger(__name__)
    logger.setLevel(logging.INFO)
    logger.handlers.clear()
    logger.propagate = False

    if not is_main_process(args):
        logger.addHandler(logging.NullHandler())
        return logger

    formatter = logging.Formatter(
        fmt="%(asctime)s | %(levelname)s | %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )
    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(formatter)
    file_handler = logging.FileHandler(Path(log_dir) / "train.log", encoding="utf-8")
    file_handler.setFormatter(formatter)
    logger.addHandler(stream_handler)
    logger.addHandler(file_handler)
    return logger


def setup_distributed(args):
    if "RANK" not in os.environ or "WORLD_SIZE" not in os.environ:
        args.rank = 0
        args.local_rank = 0
        args.world_size = 1
        args.distributed = False
        args.device = "cuda:0" if torch.cuda.is_available() else "cpu"
        return

    args.rank = int(os.environ["RANK"])
    args.local_rank = int(os.environ.get("LOCAL_RANK", 0))
    args.world_size = int(os.environ["WORLD_SIZE"])
    args.distributed = args.world_size > 1
    backend = "nccl" if torch.cuda.is_available() else "gloo"
    if torch.cuda.is_available():
        torch.cuda.set_device(args.local_rank)
        args.device = f"cuda:{args.local_rank}"
        os.environ.setdefault("NCCL_ASYNC_ERROR_HANDLING", "1")
        os.environ.setdefault("NCCL_BLOCKING_WAIT", "1")
    else:
        args.device = "cpu"
    dist.init_process_group(backend=backend, timeout=timedelta(minutes=args.dist_timeout_minutes))


def install_error_logging(output_dir, args, logger):
    error_log = Path(output_dir) / f"fatal_rank_{args.rank}.log"
    fault_log = Path(output_dir) / f"faulthandler_rank_{args.rank}.log"

    fault_file = fault_log.open("a", encoding="utf-8")
    _FAULT_LOG_FILES.append(fault_file)
    faulthandler.enable(file=fault_file, all_threads=True)

    def excepthook(exc_type, exc_value, exc_traceback):
        message = "".join(traceback.format_exception(exc_type, exc_value, exc_traceback))
        with error_log.open("a", encoding="utf-8") as f:
            f.write(f"\n===== Uncaught exception on rank {args.rank} at {datetime.now().isoformat()} =====\n")
            f.write(message)
        logger.error("Uncaught exception on rank %d:\n%s", args.rank, message)
        sys.__excepthook__(exc_type, exc_value, exc_traceback)

    sys.excepthook = excepthook


def broadcast_value(args, value):
    if not getattr(args, "distributed", False):
        return value
    values = [value]
    dist.broadcast_object_list(values, src=0)
    return values[0]


def default_name(args):
    model_name = args.model.replace("/", "-")
    date_str = datetime.now().strftime("%Y_%m_%d-%H_%M_%S")
    return "-".join(
        [
            date_str,
            f"model_{model_name}",
            f"lr_{args.lr}",
            f"b_{args.batch_size}",
            f"j_{args.workers}",
            f"p_{args.precision}",
            f"obj_{args.train_objective}",
            "ood",
        ]
    )


def resolve_output_dir(args):
    if args.name is None and is_main_process(args):
        args.name = default_name(args)
    args.name = broadcast_value(args, args.name)
    if args.output_dir:
        return Path(args.output_dir)
    return Path(args.logs) / args.name


def prepare_managed_outputs(output_dir, checkpoint_dir, resume):
    """Reset files owned by this workflow and enforce the seven-checkpoint contract."""
    allowed_checkpoint_names = set(BEST_CHECKPOINT_FILENAMES.values())
    if not resume:
        for path in [
            output_dir / "metrics.csv",
            output_dir / "time.csv",
            output_dir / "latest_metrics.json",
            output_dir / "final_result" / "epoch_results.csv",
            output_dir / "final_result" / "best_summary.json",
        ]:
            if path.exists():
                path.unlink()
        for filename in allowed_checkpoint_names:
            path = checkpoint_dir / filename
            if path.exists():
                path.unlink()
        epoch_weights_dir = checkpoint_dir / "epochs"
        if epoch_weights_dir.exists():
            for path in epoch_weights_dir.glob("*.pt"):
                path.unlink()

    # This runs only after --resume has been loaded, so even a legacy resume file
    # inside this directory can now be safely removed. Per-epoch snapshots live in
    # the "epochs" subdirectory and are excluded from this cleanup.
    for path in checkpoint_dir.glob("*.pt"):
        if path.name not in allowed_checkpoint_names:
            path.unlink()


def load_best_summary(path, checkpoint_dir, args):
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as f:
        summary = json.load(f)
    if not isinstance(summary, dict):
        raise ValueError(f"Invalid best summary (expected a JSON object): {path}")

    expected_metrics = {
        split: args.classification_best_metric for split in CLASSIFICATION_SPLITS
    }
    expected_metrics.update(
        {
            "ItoT": args.itot_best_metric,
            "TtoI": args.ttoi_best_metric,
        }
    )
    validated_summary = {}
    for result_type, item in summary.items():
        if result_type not in expected_metrics:
            continue
        if not isinstance(item, dict) or "best_epoch" not in item or "best_value" not in item:
            raise ValueError(f"Invalid {result_type!r} entry in best summary: {path}")
        if item.get("best_metric") != expected_metrics[result_type]:
            raise ValueError(
                f"Cannot resume with a different best metric for {result_type}: "
                f"summary uses {item.get('best_metric')!r}, current run uses {expected_metrics[result_type]!r}."
            )
        checkpoint_path = checkpoint_dir / BEST_CHECKPOINT_FILENAMES[result_type]
        if checkpoint_path.is_file():
            item["checkpoint"] = str(checkpoint_path)
            validated_summary[result_type] = item
    return validated_summary


def run_epoch_evaluations(model, tokenizer, classification_splits, retrieval_split, retrieval_split_1000, epoch, args, logger):
    classification_results = {}
    eval_seconds = {}
    for split_info in classification_splits:
        split = split_info["split"]
        start = time.time()
        metrics, _ = evaluate_zero_shot(
            model,
            split_info["loader"],
            tokenizer,
            split_info["class_names"],
            epoch=epoch,
            args=args,
            progress=is_main_process(args) and not args.no_progress,
        )
        eval_seconds[split] = time.time() - start
        classification_results[split] = metrics
        if is_main_process(args):
            logger.info(
                "Classification eval | epoch=%03d split=%s top1=%.6f top5=%.6f "
                "macro_top1=%.6f macro_top5=%.6f macro_f1=%.6f time=%.1fs",
                epoch,
                split,
                metrics["top1"],
                metrics["top5"],
                metrics["macro_top1"],
                metrics["macro_top5"],
                metrics["macro_f1"],
                eval_seconds[split],
            )

    retrieval_start = time.time()
    retrieval_results = evaluate_retrieval(model, retrieval_split, args)
    eval_seconds["retrieval"] = time.time() - retrieval_start
    retrieval_results_1000 = None
    if retrieval_split_1000 is not None:
        retrieval_start = time.time()
        retrieval_results_1000 = evaluate_retrieval(model, retrieval_split_1000, args)
        eval_seconds["retrieval_1000"] = time.time() - retrieval_start
    if not is_main_process(args):
        return None

    logger.info(
        "Retrieval eval | epoch=%03d ItoT_R1=%.6f TtoI_R1=%.6f samples=%d time=%.1fs",
        epoch,
        retrieval_results["i2t_r1"],
        retrieval_results["t2i_r1"],
        retrieval_results["num_samples"],
        eval_seconds["retrieval"],
    )
    if retrieval_results_1000 is not None:
        logger.info(
            "Retrieval-1000 eval | epoch=%03d ItoT_R1=%.6f ItoT_R5=%.6f TtoI_R1=%.6f "
            "TtoI_R5=%.6f samples=%d time=%.1fs",
            epoch,
            retrieval_results_1000["i2t_r1"],
            retrieval_results_1000["i2t_r5"],
            retrieval_results_1000["t2i_r1"],
            retrieval_results_1000["t2i_r5"],
            retrieval_results_1000["num_samples"],
            eval_seconds["retrieval_1000"],
        )
    return classification_results, retrieval_results, retrieval_results_1000, eval_seconds


def make_final_result_row(epoch, train_metrics, classification_results, retrieval_results, retrieval_results_1000, eval_seconds, args):
    row = {
        "epoch": epoch,
        "train_loss": train_metrics["loss"],
        "train_top1": train_metrics["top1"],
        "train_top5": train_metrics["top5"],
    }
    for split in CLASSIFICATION_SPLITS:
        for metric in CLASSIFICATION_METRICS:
            row[f"{split}_{metric}"] = classification_results[split][metric]
    for metric in RETRIEVAL_METRICS:
        row[metric] = retrieval_results[metric]
    for metric in RETRIEVAL_METRICS_1000:
        # Reported only; never used for best-checkpoint selection (see
        # update_best_checkpoints, which keys off "ItoT"/"TtoI" of the primary pool).
        row[f"retrieval_1000_{metric}"] = (
            retrieval_results_1000.get(metric) if retrieval_results_1000 else None
        )
    row.update(
        {
            split: classification_results[split][args.classification_best_metric]
            for split in CLASSIFICATION_SPLITS
        }
    )
    row.update(
        {
            "ItoT": retrieval_results[args.itot_best_metric],
            "TtoI": retrieval_results[args.ttoi_best_metric],
        }
    )
    row.update(
        {
            f"{split}_eval_seconds": eval_seconds[split]
            for split in CLASSIFICATION_SPLITS
        }
    )
    row["retrieval_eval_seconds"] = eval_seconds["retrieval"]
    return row


def update_best_checkpoints(checkpoint_dir, best_summary, row, model, optimizer, scaler, epoch, args, logger):
    metric_keys = {split: split for split in CLASSIFICATION_SPLITS}
    metric_keys.update(
        {
            "ItoT": "ItoT",
            "TtoI": "TtoI",
        }
    )
    improved = []
    for result_type, metric_key in metric_keys.items():
        value = float(row[metric_key])
        if not math.isfinite(value):
            raise ValueError(
                f"Cannot select a best checkpoint for {result_type}: {metric_key} is not finite ({value})."
            )
        previous = best_summary.get(result_type)
        if previous is not None and value <= float(previous["best_value"]):
            continue

        checkpoint_path = checkpoint_dir / BEST_CHECKPOINT_FILENAMES[result_type]
        temporary_path = checkpoint_path.with_suffix(".tmp")
        save_checkpoint(
            temporary_path,
            model,
            optimizer,
            scaler,
            epoch,
            epoch,
            value,
            args,
            row,
        )
        os.replace(temporary_path, checkpoint_path)
        if result_type == "ItoT":
            best_metric = args.itot_best_metric
        elif result_type == "TtoI":
            best_metric = args.ttoi_best_metric
        else:
            best_metric = args.classification_best_metric
        best_summary[result_type] = {
            "best_metric": best_metric,
            "best_epoch": epoch,
            "best_value": value,
            "checkpoint": str(checkpoint_path),
        }
        improved.append(result_type)
        logger.info(
            "Updated best checkpoint | type=%s epoch=%03d metric=%s value=%.6f path=%s",
            result_type,
            epoch,
            best_summary[result_type]["best_metric"],
            value,
            checkpoint_path,
        )
    return improved


def save_epoch_weights(checkpoint_dir, model, epoch, row, args):
    """Persist a lightweight per-epoch weights snapshot (model state only, no optimizer).

    Stored under checkpoints/epochs/epoch_XXX.pt so the seven best-checkpoint
    contract (checkpoints/*.pt) stays untouched. Writes to a temporary file and
    renames atomically so a crash cannot leave a half-written snapshot.
    """
    epoch_dir = checkpoint_dir / "epochs"
    epoch_dir.mkdir(parents=True, exist_ok=True)
    path = epoch_dir / f"epoch_{epoch:03d}.pt"
    temporary_path = path.with_suffix(".tmp")
    snapshot = {
        "epoch": epoch,
        "name": args.name,
        "state_dict": unwrap_model(model).state_dict(),
        "metrics": row,
    }
    torch.save(snapshot, temporary_path)
    os.replace(temporary_path, path)
    return path


