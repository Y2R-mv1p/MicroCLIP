def validate_args(args):
    positive_values = {
        "epochs": args.epochs,
        "batch_size": args.batch_size,
        "eval_batch_size": args.eval_batch_size or args.batch_size,
        "prefetch_factor": args.prefetch_factor,
        "similarity_chunk_size": args.similarity_chunk_size,
    }
    for name, value in positive_values.items():
        if value <= 0:
            raise ValueError(f"--{name.replace('_', '-')} must be positive, got {value}.")
    if args.workers < 0:
        raise ValueError(f"--workers must be non-negative, got {args.workers}.")
    if (args.semantic_structure_tsv is None) != (args.semantic_cell_tsv is None):
        raise ValueError("--semantic-structure-tsv and --semantic-cell-tsv must be provided together.")
    if args.semantic_replace_mode not in ("both", "structure-only", "cell-only", "none", "random"):
        raise ValueError(f"Unsupported --semantic-replace-mode: {args.semantic_replace_mode}")
    if not 0.0 <= args.semantic_replace_structure_prob <= 1.0:
        raise ValueError(
            f"--semantic-replace-structure-prob must be in [0, 1], got {args.semantic_replace_structure_prob}."
        )
    if not 0.0 <= args.semantic_replace_cell_prob <= 1.0:
        raise ValueError(
            f"--semantic-replace-cell-prob must be in [0, 1], got {args.semantic_replace_cell_prob}."
        )
    if args.train_long_caption_mode == "three-way":
        for prob_name, prob_value in (
            ("--long-caption-sample-prob", args.long_caption_sample_prob),
            ("--short-caption-sample-prob", args.short_caption_sample_prob),
            ("--rewrite-caption-sample-prob", args.rewrite_caption_sample_prob),
        ):
            if not 0.0 <= prob_value <= 1.0:
                raise ValueError(f"{prob_name} must be in [0, 1], got {prob_value}.")
        if not math.isclose(
            args.long_caption_sample_prob
            + args.short_caption_sample_prob
            + args.rewrite_caption_sample_prob,
            1.0,
            abs_tol=1e-6,
        ):
            raise ValueError(
                "In three-way mode, --long-caption-sample-prob + --short-caption-sample-prob "
                "+ --rewrite-caption-sample-prob must sum to 1."
            )
    if args.force_image_size is not None:
        if len(args.force_image_size) not in (1, 2) or any(size <= 0 for size in args.force_image_size):
            raise ValueError(
                "--force-image-size expects one or two positive integers, "
                f"got {args.force_image_size}."
            )
        args.force_image_size = (
            args.force_image_size[0] if len(args.force_image_size) == 1 else tuple(args.force_image_size)
        )
    if args.force_context_length is not None and args.force_context_length < 2:
        raise ValueError(f"--force-context-length must be at least 2, got {args.force_context_length}.")
    if args.metaclip_balance_counts and args.metaclip_balance_threshold <= 0:
        raise ValueError(
            "--metaclip-balance-threshold must be positive when MetaCLIP balancing is enabled."
        )
    if args.metaclip_balance_source != "txt" and not (
        args.metaclip_balance_source.startswith("json:") and args.metaclip_balance_source[5:]
    ):
        raise ValueError("--metaclip-balance-source must be 'txt' or 'json:<dotted-key>'.")


